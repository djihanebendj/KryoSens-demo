"""Rule 7 (docs/COPILOT.md §8): structured diagnostic content is rendered by the application, never authored by
the LLM.

``rank_diagnostic_checks`` returns a Phase 6 ``DiagnosticReport``. Before any of it reaches a user, this module
re-validates the report from its serialised form (so a caller cannot hand in an object that skipped the Phase 6
model validators), requires every hypothesis to be ``PROPOSED`` and rule-generated (``generated_by`` starts with
``rules:``), checks that each hypothesis is grounded in a listed fact and in a ranked next check, and then renders
the result through fixed application templates.

The rendered text uses two fixed claim labels:

* ``MODEL_INFERENCE`` -- a diagnostic hypothesis. It is never promoted to a confirmed fault; certainty is
  ``UNKNOWN`` until a recorded test resolves it.
* ``SYSTEM_RECOMMENDATION`` -- a ranked next check: a work priority, not a confidence in an explanation.

When the report is missing or invalid, callers must render the ``UNKNOWN`` / insufficient-evidence template
instead of any LLM prose. ``contains_diagnostic_claim`` is the deterministic secondary check for an LLM answer that
tries to supply diagnostic labels without a validated report.
"""

from __future__ import annotations

import re

from coldsense.core.governance import HypothesisStatus
from coldsense.domains.cold_room.diagnostics import DiagnosisStatus, DiagnosticReport

MODEL_INFERENCE = "MODEL_INFERENCE"
SYSTEM_RECOMMENDATION = "SYSTEM_RECOMMENDATION"
UNKNOWN = "UNKNOWN"
OBSERVED_FACT = "OBSERVED_FACT"

# Fixed labels plus the headings a model might use to imitate a diagnostic report. The final-answer text check is
# secondary: the primary control is that diagnostic content is only rendered from a validated report.
DIAGNOSTIC_MARKERS = re.compile(
    r"\b(?:MODEL_INFERENCE|SYSTEM_RECOMMENDATION|OBSERVED_FACT|NEXT[- ]BEST[- ]CHECK|DIAGNOSIS|HYPOTHESIS)\b",
    re.I,
)


class DiagnosticValidationError(ValueError):
    """The report cannot be shown: it is malformed, not rule-generated, or not internally grounded."""


def contains_diagnostic_claim(text: str) -> bool:
    """True if an LLM answer tries to present diagnostic labels/report structure. Without a validated report the
    turn must fail closed to UNKNOWN."""
    return bool(DIAGNOSTIC_MARKERS.search(text or ""))


def validate_report(value: object) -> DiagnosticReport:
    """Re-validate a report and enforce the Phase 8 rules that make it safe to render.

    ``value`` may be a ``DiagnosticReport`` or its JSON-compatible dump (what a tool result carries). Re-validating
    from the dump runs the Phase 6 consistency validator again; this is deliberate, since a caller could otherwise
    mutate a model after construction.
    """
    try:
        if isinstance(value, DiagnosticReport):
            report = DiagnosticReport.model_validate(value.model_dump())
        else:
            report = DiagnosticReport.model_validate(value)
    except Exception as e:                                        # noqa: BLE001 - any validation failure is a refusal
        raise DiagnosticValidationError(f"invalid Phase 6 diagnostic report: {type(e).__name__}") from None

    facts = {f.fact_id for f in report.observed_facts}
    ranked = {c.check_id for c in report.next_checks}
    for h in report.hypotheses:
        if h.status != HypothesisStatus.PROPOSED:
            raise DiagnosticValidationError(f"hypothesis {h.id} is {h.status.value}, not PROPOSED")
        if not h.generated_by.startswith("rules:"):
            raise DiagnosticValidationError(f"hypothesis {h.id} was not generated by the application rules")
        fact_id = h.motivating_observation.split(" ", 1)[0]
        if fact_id not in facts:
            raise DiagnosticValidationError(f"hypothesis {h.id} is not grounded in a listed observed fact")
        test = h.test.split(" ", 3)
        if len(test) < 3 or test[0:2] != ["next", "check"] or test[2].rstrip(":") not in ranked:
            raise DiagnosticValidationError(f"hypothesis {h.id} is not tied to a ranked next check")

    for f in report.findings:
        for hid in f.hypothesis_ids:
            if hid not in {h.id for h in report.hypotheses}:
                raise DiagnosticValidationError(f"finding {f.finding_id} references an unknown hypothesis {hid}")
    return report


def _items(values: list[str], empty: str = "none recorded") -> str:
    return "; ".join(values) if values else empty


def _render_report(report: DiagnosticReport) -> list[str]:
    lines = [
        "DIAGNOSTIC RESULT (application-generated from a validated Phase 6 report)",
        f"Status: {report.status.value}",
        f"Evidence class: {report.data_evidence.value}",
        f"Certainty: {UNKNOWN}",
    ]
    if report.status == DiagnosisStatus.INSUFFICIENT_EVIDENCE:
        lines.append(f"{UNKNOWN}: {report.refusal_reason or 'no reason was recorded'}")
        lines.append("No diagnostic hypothesis is proposed, so no fault is confirmed.")
    elif report.status == DiagnosisStatus.NO_FINDING:
        lines.append("No sustained excursion beyond the stated limit was found; no hypothesis is proposed.")
    else:
        lines.append("The following are hypotheses, not a confirmed fault.")
    if report.as_of is not None:
        lines.append(f"As of: {report.as_of:%Y-%m-%d %H:%M}")
    lines.append("")

    if report.observed_facts:
        lines.append(f"{OBSERVED_FACT} (what the records say; not an interpretation of cause):")
        for fact in report.observed_facts:
            window = ""
            if fact.start is not None or fact.end is not None:
                window = (f" [{fact.start:%Y-%m-%d %H:%M}" if fact.start else " ["
                          ) + (f" to {fact.end:%Y-%m-%d %H:%M}]" if fact.end else "]")
            lines.append(f"  [{fact.fact_id}] {fact.statement}{window}")
        lines.append("")

    if report.hypotheses:
        lines.append(f"{MODEL_INFERENCE} (hypotheses only; never a confirmed fault):")
        for h in report.hypotheses:
            lines.append(f"  - {h.id}: {h.statement}")
            lines.append(f"      supporting evidence: {_items(h.supporting_evidence)}")
            lines.append(f"      contradicting evidence: {_items(h.contradicting_evidence)}")
            lines.append(f"      missing evidence: {_items(h.data_needed)}")
            lines.append(f"      test: {h.test}")
            lines.append(f"      success criteria: {h.success_criteria}")
            if h.alternatives:
                lines.append(f"      alternatives: {_items(h.alternatives)}")
        lines.append("")

    if report.next_checks:
        lines.append(f"{SYSTEM_RECOMMENDATION} (a ranked work priority, not a confidence in an explanation):")
        for c in report.next_checks:
            lines.append(f"  {c.rank}. [{c.check_id}] {c.action}")
            lines.append(f"      evidence: {_items(c.evidence)}")
            lines.append(f"      expected information: {_items(c.expected_information)}")
            lines.append(f"      safety: {c.safety.value}; {c.safety_note}")
        lines.append("")

    if report.limitations:
        lines.append("Limitations:")
        lines.extend(f"  - {x}" for x in report.limitations)
    return lines


def render_diagnostic(report: object) -> str:
    """Render a validated report through the fixed application template. Raises DiagnosticValidationError."""
    return "\n".join(_render_report(validate_report(report))).rstrip()


def unknown_diagnostic(reason: str = "no validated Phase 6 diagnostic report is available for this case") -> str:
    """The fail-closed template used when diagnostic content is requested without a report the application can
    validate. It states no hypothesis and no fault."""
    return (f"DIAGNOSTIC RESULT (application-generated)\nStatus: {UNKNOWN}\nCertainty: {UNKNOWN}\n"
            f"{UNKNOWN}: {reason}. No hypothesis or confirmed fault can be stated. "
            "Have a qualified refrigeration technician assess this on site.")


__all__ = ["DiagnosticValidationError", "MODEL_INFERENCE", "SYSTEM_RECOMMENDATION", "UNKNOWN",
           "contains_diagnostic_claim", "render_diagnostic", "unknown_diagnostic", "validate_report"]
