"""Step 5 (Evidence Board) and Step 6 (Structured Diagnostics, Template Hypotheses & Next Best Checks).

Enforces:
- Facts, Model Inferences, and Recommendations are strictly separated, each with its provenance
  and EvidenceClass (REAL, SIMULATED, EXPECTED, UNVALIDATED).
- Rule 7: Hypotheses are rendered strictly from locked structured templates—never generated by an LLM.
- Hypotheses are never confirmed faults; their verification_status is always UNKNOWN until Step 9.
"""

from __future__ import annotations

from typing import Dict, List

from coldsense.models import (
    CaseRecord,
    EvidenceBoard,
    EvidenceCategory,
    EvidenceClass,
    EvidenceItem,
    EventType,
    Hypothesis,
    NextBestCheck,
    PredictionRefusal,
    PredictionSuccess,
    VerificationStatus,
    WorkflowStep,
)

# Locked deterministic templates for Rule 7 (Hypotheses come from templates, never LLM free-text)
HYPOTHESIS_TEMPLATES: Dict[str, str] = {
    "TPL-HYP-POWER-LOSS": (
        "HYPOTHESIS [Unconfirmed]: Primary electrical supply interruption or open compressor circuit breaker "
        "caused unpowered thermal drift from {start_temp_c:.2f} C to {peak_temp_c:.2f} C over {duration_min:.1f} minutes."
    ),
    "TPL-HYP-ENVELOPE-LEAK": (
        "HYPOTHESIS [Unconfirmed]: Accelerated thermal infiltration (estimated tau = {tau_hours:.2f} hours) "
        "indicates compromised door perimeter gasket, unsealed conduit penetration, or degraded panel insulation."
    ),
    "TPL-HYP-DOOR-AJAR": (
        "HYPOTHESIS [Unconfirmed]: Door ajar or frequent loading traffic produced transient warm air ingress "
        "(peak {peak_temp_c:.2f} C across {event_count} door disturbance event(s))."
    ),
    "TPL-HYP-SENSOR-DATA-FAULT": (
        "HYPOTHESIS [Unconfirmed]: Telemetry logging fault, sensor dropout, or uncalibrated probe prevented "
        "reliable thermal parameter identification ({refusal_reason})."
    ),
}


def build_evidence_board(case: CaseRecord) -> EvidenceBoard:
    """Step 5: Build the three-column Evidence Board (Facts, Model Inferences, Recommendations)
    with explicit provenance and evidence classes. Unlocks Step 6 (NEXT_BEST_CHECK).
    """
    if not case.is_step_unlocked(WorkflowStep.EVIDENCE) or case.prediction is None:
        raise ValueError("Step 5 (Evidence) requires Step 4 (Prediction/Refusal) to be completed first.")

    facts: List[EvidenceItem] = []
    inferences: List[EvidenceItem] = []
    recommendations: List[EvidenceItem] = []

    dq = case.data_quality
    if dq is not None:
        facts.append(
            EvidenceItem(
                evidence_id="ev-fact-dq",
                category=EvidenceCategory.FACT,
                evidence_class=case.evidence_class,
                title="Sensor Log Completeness & Cadence",
                statement=(
                    f"Log contains {dq.valid_rows} valid readings at {dq.median_cadence_sec:.0f}s median cadence "
                    f"with {dq.gap_count} sampling gap(s) (completeness {dq.completeness_ratio:.1%})."
                ),
                provenance_source=f"DataQualityReport(case_id={case.case_id})",
                supports=["Telemetry cadence verification", "Reliability gate sample check"],
                does_not_support=["Root cause of equipment fault without physical inspection"],
                numeric_values={
                    "valid_rows": float(dq.valid_rows),
                    "median_cadence_sec": float(dq.median_cadence_sec),
                    "gap_count": float(dq.gap_count),
                    "completeness_ratio": float(dq.completeness_ratio),
                },
            )
        )

    for ev in case.events:
        facts.append(
            EvidenceItem(
                evidence_id=f"ev-fact-{ev.event_id}",
                category=EvidenceCategory.FACT,
                evidence_class=ev.evidence_class,
                title=f"Observed {ev.event_type.value} Window",
                statement=(
                    f"Observed {ev.event_type.value} from {ev.start_iso} to {ev.end_iso} "
                    f"(duration {ev.duration_sec / 60.0:.1f} min, start {ev.start_temp_c:.2f} C, "
                    f"peak {ev.peak_temp_c:.2f} C, drift rate {ev.drift_rate_c_per_hour:+.2f} C/hr)."
                ),
                provenance_source=f"TemperatureEvent(id={ev.event_id}, rows={ev.start_index}..{ev.end_index})",
                supports=[f"Occurrence of {ev.event_type.value} thermal excursion"],
                does_not_support=["Confirmed component failure without technician verification"],
                numeric_values={
                    "duration_sec": ev.duration_sec,
                    "duration_min": round(ev.duration_sec / 60.0, 1),
                    "start_temp_c": ev.start_temp_c,
                    "peak_temp_c": ev.peak_temp_c,
                    "drift_rate_c_per_hour": ev.drift_rate_c_per_hour,
                },
            )
        )

    pred = case.prediction
    if isinstance(pred, PredictionSuccess):
        inferences.append(
            EvidenceItem(
                evidence_id="ev-inf-thermal-fit",
                category=EvidenceCategory.MODEL_INFERENCE,
                evidence_class=pred.evidence_class,
                title="First-Order Thermal Time Constant & Drift Fit",
                statement=(
                    f"Fitted first-order thermal time constant tau = {pred.time_constant_tau_hours:.2f} hours "
                    f"({pred.time_constant_tau_sec:.0f} s) toward ambient {pred.ambient_temp_c:.1f} C "
                    f"with R^2 = {pred.r_squared:.4f} and 95% uncertainty half-width +/-{pred.uncertainty_95_halfwidth_c:.2f} C."
                ),
                provenance_source=f"FirstOrderThermalModel(event_id={pred.event_id})",
                supports=[
                    "Passive exponential thermal drift dynamics",
                    f"Estimated time to {pred.critical_threshold_c:.1f} C threshold: {pred.estimated_time_to_threshold_sec or 0.0:.0f} s",
                ],
                does_not_support=[
                    "Exact internal product core temperature without product probe",
                    "Confirmed electrical vs mechanical fault cause",
                ],
                numeric_values={
                    "tau_hours": pred.time_constant_tau_hours,
                    "tau_sec": pred.time_constant_tau_sec,
                    "ambient_temp_c": pred.ambient_temp_c,
                    "r_squared": pred.r_squared,
                    "thermal_model_rmse_c": pred.thermal_model_rmse_c,
                    "naive_baseline_rmse_c": pred.naive_baseline_rmse_c,
                },
            )
        )
        recommendations.append(
            EvidenceItem(
                evidence_id="ev-rec-power-envelope",
                category=EvidenceCategory.RECOMMENDATION,
                evidence_class=EvidenceClass.EXPECTED,
                title="Verify Power Supply & Cold-Room Thermal Envelope",
                statement=(
                    f"Execute ranked physical checks to confirm why cooling ceased during {pred.event_id} "
                    f"and verify door gasket integrity before cold room reaches {pred.critical_threshold_c:.1f} C."
                ),
                provenance_source="ColdSenseDiagnosticEngine(v1)",
                supports=["Prioritized on-site technician inspection sequence"],
                does_not_support=["Automated fault closure without technician confirmation"],
                numeric_values={"critical_threshold_c": pred.critical_threshold_c},
            )
        )
    elif isinstance(pred, PredictionRefusal):
        inferences.append(
            EvidenceItem(
                evidence_id="ev-inf-refusal",
                category=EvidenceCategory.MODEL_INFERENCE,
                evidence_class=pred.evidence_class,
                title=f"Reliability Gate Refusal ({pred.reason_code.value})",
                statement=pred.refusal_explanation,
                provenance_source="ReliabilityGate(v1)",
                supports=["Refusal to extrapolate an untrustworthy temperature curve"],
                does_not_support=["Any numerical temperature drift forecast for this event"],
                numeric_values=pred.diagnostics_metrics,
            )
        )
        recommendations.append(
            EvidenceItem(
                evidence_id="ev-rec-sensor-audit",
                category=EvidenceCategory.RECOMMENDATION,
                evidence_class=EvidenceClass.EXPECTED,
                title="Inspect Data Logger & Temperature Probe Placement",
                statement=(
                    "Verify temperature logger sampling configuration, battery state, and probe physical mounting "
                    "before relying on automated drift forecasts."
                ),
                provenance_source="ColdSenseDiagnosticEngine(v1)",
                supports=["Restoring valid telemetry collection"],
                does_not_support=["Confirming refrigeration hardware health from degraded data"],
                numeric_values={},
            )
        )

    board = EvidenceBoard(
        case_id=case.case_id,
        evidence_class=case.evidence_class,
        facts=facts,
        model_inferences=inferences,
        recommendations=recommendations,
    )
    case.evidence_board = board
    if case.unlocked_step < int(WorkflowStep.NEXT_BEST_CHECK):
        case.unlocked_step = int(WorkflowStep.NEXT_BEST_CHECK)
    return board


def generate_diagnostics_and_next_checks(
    case: CaseRecord,
) -> Tuple[List[Hypothesis], List[NextBestCheck]]:
    """Step 6: Produce template-rendered Hypotheses (Rule 7) and ranked Next Best Checks.

    Unlocks Step 7 (COPILOT), Step 8 (TECHNICIAN_FINDING), Step 9 (VERIFICATION), and Step 10 (REPORT).
    """
    if not case.is_step_unlocked(WorkflowStep.NEXT_BEST_CHECK) or case.evidence_board is None:
        raise ValueError("Step 6 (Next Best Check) requires Step 5 (Evidence Board) to be completed first.")

    hypotheses: List[Hypothesis] = []
    checks: List[NextBestCheck] = []
    pred = case.prediction

    power_events = [e for e in case.events if e.event_type == EventType.POWER_CUT]
    door_events = [e for e in case.events if e.event_type == EventType.DOOR_OPEN]

    if power_events:
        pe = power_events[0]
        stmt = HYPOTHESIS_TEMPLATES["TPL-HYP-POWER-LOSS"].format(
            start_temp_c=pe.start_temp_c,
            peak_temp_c=pe.peak_temp_c,
            duration_min=pe.duration_sec / 60.0,
        )
        hypotheses.append(
            Hypothesis(
                hypothesis_id="hyp-001-power-loss",
                template_id="TPL-HYP-POWER-LOSS",
                title="Primary Power Interruption or Compressor Supply Trip",
                rendered_statement=stmt,
                evidence_class=case.evidence_class,
                supporting_evidence_ids=[f"ev-fact-{pe.event_id}"],
                contradicting_evidence_ids=[],
                prior_plausibility_rank=1,
                verification_status=VerificationStatus.UNKNOWN,
            )
        )
        checks.append(
            NextBestCheck(
                check_id="chk-001-supply-panel",
                rank=1,
                title="Inspect Main Supply Breaker, Phase Monitor & Controller Alarm Log",
                inspection_procedure=(
                    "Visually inspect the cold-room main isolator, circuit breaker state, phase-failure relay LED, "
                    "and digital controller alarm history for power-loss or trip codes."
                ),
                target_hypothesis_ids=["hyp-001-power-loss"],
                confirm_indicator="Tripped breaker, phase-loss alarm code, or utility outage log entry present.",
                reject_indicator="Continuous voltage verified at supply terminals with no trip or outage record.",
                estimated_minutes=5,
                evidence_class=EvidenceClass.EXPECTED,
            )
        )

    if isinstance(pred, PredictionSuccess):
        stmt_env = HYPOTHESIS_TEMPLATES["TPL-HYP-ENVELOPE-LEAK"].format(
            tau_hours=pred.time_constant_tau_hours
        )
        hypotheses.append(
            Hypothesis(
                hypothesis_id="hyp-002-envelope-leak",
                template_id="TPL-HYP-ENVELOPE-LEAK",
                title="Door Gasket Degradation or Thermal Envelope Infiltration",
                rendered_statement=stmt_env,
                evidence_class=case.evidence_class,
                supporting_evidence_ids=["ev-inf-thermal-fit"],
                contradicting_evidence_ids=[],
                prior_plausibility_rank=len(hypotheses) + 1,
                verification_status=VerificationStatus.UNKNOWN,
            )
        )
        checks.append(
            NextBestCheck(
                check_id="chk-002-door-gasket",
                rank=len(checks) + 1,
                title="Perform Perimeter Door Gasket Paper-Drag & Frost Inspection",
                inspection_procedure=(
                    "Inspect the full perimeter of the cold-room door seal for tears, ice build-up, or warping, "
                    "and perform a paper-strip tension check at all four corners."
                ),
                target_hypothesis_ids=["hyp-002-envelope-leak"],
                confirm_indicator="Visible gap, localized frost/condensation trail, or loose paper drag along gasket.",
                reject_indicator="Uniform compression seal around entire perimeter with zero localized frost.",
                estimated_minutes=10,
                evidence_class=EvidenceClass.EXPECTED,
            )
        )

    if door_events:
        peak_door = max(e.peak_temp_c for e in door_events)
        stmt_door = HYPOTHESIS_TEMPLATES["TPL-HYP-DOOR-AJAR"].format(
            peak_temp_c=peak_door,
            event_count=len(door_events),
        )
        hypotheses.append(
            Hypothesis(
                hypothesis_id="hyp-003-door-ajar",
                template_id="TPL-HYP-DOOR-AJAR",
                title="Door Left Ajar or Strip Curtain Obstruction",
                rendered_statement=stmt_door,
                evidence_class=case.evidence_class,
                supporting_evidence_ids=[f"ev-fact-{door_events[0].event_id}"],
                contradicting_evidence_ids=[],
                prior_plausibility_rank=len(hypotheses) + 1,
                verification_status=VerificationStatus.UNKNOWN,
            )
        )
        checks.append(
            NextBestCheck(
                check_id="chk-003-door-switch",
                rank=len(checks) + 1,
                title="Verify Door Microswitch Alignment, Closer Mechanism & Strip Curtains",
                inspection_procedure=(
                    "Check automatic door closer tension, PVC strip curtain overlap, and door reed/microswitch "
                    "actuation when the door latches."
                ),
                target_hypothesis_ids=["hyp-003-door-ajar"],
                confirm_indicator="Door fails to self-latch, strip curtains hung up, or switch stuck in open state.",
                reject_indicator="Door latches tightly and switch state transitions cleanly on closure.",
                estimated_minutes=8,
                evidence_class=EvidenceClass.EXPECTED,
            )
        )

    if isinstance(pred, PredictionRefusal) or not hypotheses:
        reason_str = pred.reason_code.value if isinstance(pred, PredictionRefusal) else "NO_EXCURSION"
        stmt_sensor = HYPOTHESIS_TEMPLATES["TPL-HYP-SENSOR-DATA-FAULT"].format(
            refusal_reason=reason_str
        )
        hypotheses.append(
            Hypothesis(
                hypothesis_id="hyp-004-sensor-fault",
                template_id="TPL-HYP-SENSOR-DATA-FAULT",
                title="Temperature Logger Dropout or Uncalibrated Probe Fault",
                rendered_statement=stmt_sensor,
                evidence_class=case.evidence_class,
                supporting_evidence_ids=["ev-fact-dq"],
                contradicting_evidence_ids=[],
                prior_plausibility_rank=len(hypotheses) + 1,
                verification_status=VerificationStatus.UNKNOWN,
            )
        )
        checks.append(
            NextBestCheck(
                check_id="chk-004-probe-icebath",
                rank=len(checks) + 1,
                title="Audit Logger Sampling Settings & Verify Probe in Reference Ice Bath",
                inspection_procedure=(
                    "Check logger memory/battery, confirm probe is not mounted directly in evaporator discharge air, "
                    "and compare reading against a calibrated reference thermometer."
                ),
                target_hypothesis_ids=["hyp-004-sensor-fault"],
                confirm_indicator="Logger buffer errors, loose probe wiring, or >0.5 C deviation from reference probe.",
                reject_indicator="Probe passes reference check and logger records continuous intervals.",
                estimated_minutes=12,
                evidence_class=EvidenceClass.EXPECTED,
            )
        )

    case.hypotheses = hypotheses
    case.next_best_checks = checks
    if case.unlocked_step < int(WorkflowStep.REPORT):
        case.unlocked_step = int(WorkflowStep.REPORT)
    return hypotheses, checks
