"use client";

import Link from "next/link";

import { FindingCard } from "@/components/findings";
import { ProvenancePanel } from "@/components/provenance";
import { EmptyState } from "@/components/states";
import { DiagnosisRefusal, Items, Label, WorkspaceStates } from "@/components/workspace-states";
import type { InvestigationView } from "@/lib/api/types";
import { useCase } from "@/lib/case-context";
import { useCaseResource } from "@/lib/use-case-resource";

function Investigation({ v }: { v: InvestigationView }) {
  return (
    <div className="space-y-5" data-testid="investigation">
      <p className="text-sm text-slate-700">
        Read-only. Hypotheses come from Phase 6 rules over recorded evidence ({v.rules_validation}). Each is a{" "}
        <strong>{v.hypothesis_note}</strong>; recording a technician finding is not available yet (Stage 3).
      </p>
      {v.status === "INSUFFICIENT_EVIDENCE" && <DiagnosisRefusal reason={v.refusal_reason} />}
      {v.status === "NO_FINDING" && <EmptyState title="No hypothesis">No sustained excursion beyond the limits you set was found.</EmptyState>}
      {v.hypotheses.length > 0 && (
        <section className="space-y-3">
          <h2 className="text-base font-semibold">Hypotheses ({v.hypotheses.length})</h2>
          {v.hypotheses.map((h) => (
            <article key={h.id} className="space-y-2 rounded-lg border border-violet-200 bg-white p-4 text-sm" data-testid={`hypothesis-${h.id}`}>
              <header className="flex flex-wrap items-center gap-2">
                <Label kind={v.hypothesis_label} />
                <span className="rounded bg-violet-50 px-1.5 text-xs text-violet-900 ring-1 ring-violet-200">{v.hypothesis_note}</span>
                <code className="text-xs">{h.status}</code>
                <span className="font-mono text-xs text-slate-500">{h.id}</span>
              </header>
              <p className="font-medium">{h.statement}</p>
              <p className="text-xs text-slate-600">
                <Label kind="OBSERVED_FACT" /> motivated by: {h.motivating_observation}
              </p>
              <div className="grid gap-2 sm:grid-cols-2">
                <Items title="Supporting evidence" items={h.supporting_evidence} tone="text-emerald-800" />
                <Items title="Contradicting evidence" items={h.contradicting_evidence} tone="text-rose-800" testId="contradicting" />
                <Items title="Missing information (data needed)" items={h.data_needed} tone="text-amber-800" testId="missing" />
                <Items title="Alternatives still open" items={h.alternatives} />
              </div>
              <p className="text-xs">
                <Label kind="SYSTEM_RECOMMENDATION" /> next check: {h.test}
              </p>
              <p className="text-xs text-slate-600">Would be supported/refuted: {h.success_criteria}</p>
              <p className="text-xs text-slate-400">generated by {h.generated_by}</p>
            </article>
          ))}
        </section>
      )}
      {v.findings.length > 0 && (
        <section className="space-y-2">
          <h2 className="text-base font-semibold">Findings and the assessment of every explanation</h2>
          {v.findings.map((f) => (
            <FindingCard key={f.finding_id} f={f} />
          ))}
        </section>
      )}
      {v.next_checks.length > 0 && (
        <p className="text-sm">
          <Label kind={v.recommendation_label} /> {v.next_checks.length} ranked check(s): see <Link href="/next-check" className="text-sky-800 underline">Next Best Check</Link>.
        </p>
      )}
      <Items title="Limitations" items={v.limitations} />
      <ProvenancePanel p={v.provenance} />
    </div>
  );
}

export default function InvestigationPage() {
  const { api } = useCase();
  const res = useCaseResource((id) => api.getInvestigation(id), 0, true);
  return (
    <div className="space-y-4">
      <h1 className="text-xl font-semibold">Investigation</h1>
      <WorkspaceStates href="/investigation" res={res} loading="Loading the hypotheses…">
        {(v) => <Investigation v={v} />}
      </WorkspaceStates>
    </div>
  );
}
